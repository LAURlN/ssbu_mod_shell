"""Generate recipient-owned Hero neutral-B ACMD (v1.0.0).

Uses the pinned vanilla dump, preserving hitboxes, frames and resource names.
Hero fighter work flags become plugin-owned state; genuine cloned fireball work
ids retain their original layout. Mana-failure branches are excluded explicitly.
The dump's misplaced HOLD else is repaired to belong to START_M, and localized
shoot voices use the separately dumped Default/usen success scripts. No sound
or effect is replaced with a stand-in. --check verifies generated output.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
CFG = tomllib.loads((ROOT / 'paths.toml').read_text())
DONOR = ROOT / CFG['dumps']['scripts'] / 'smashline-hdr/lua2cpp_brave'
OUT = ROOT / 'src/pgwr/plugin/src/mythra/hero_neutral_b/acmd.rs'
sys.path.insert(0, str(ROOT / 'src/pgwr/tools'))
from gen_acmd import split_functions


def close_prefix(text):
    """Close a successful branch prefix; reject negative nesting."""
    depth = 0
    for ch in text:
        depth += (ch == '{') - (ch == '}')
        assert depth >= 0
    return text.rstrip() + '\n' + '}\n' * depth


def translate(name, text, weapon):
    if not weapon and name.startswith(('effect_', 'expression_')) and re.search(r'n[123]$', name):
        # Both expressions and shot effects print the unsuccessful mana arm as
        # an else on the last is_excute. The no-mana route retains its prefix.
        if 'else {' in text:
            text = close_prefix(text.split('else {', 1)[0])
    if name in ('effect_specialnhold', 'effect_specialairnhold'):
        # Printed: if !START_M { if execute {} else { if execute {} } }
        # Native conditional: if !START_M { if execute {} } else { if execute {} }
        text = text.replace('        else {', '    } else {', 1)
        at = text.index('for _') if 'for _' in text else text.rfind('}')
        before, after = text[:at], text[at:]
        pos = before.rfind('}\n')
        text = before[:pos] + before[pos + 2:] + after
    text = text.replace('let boma = agent.boma();', 'let boma = agent.module_accessor;')
    text = re.sub(r'WorkModule::is_flag\(boma, \*FIGHTER_BRAVE_STATUS_SPECIAL_N_FLAG_(\w+)\)',
                  lambda m: 'true' if m[1] == 'SUCCESS_SP' else f'super::flag(boma, super::{m[1]})', text)
    text = re.sub(r'WorkModule::on_flag\(boma, \*FIGHTER_BRAVE_STATUS_SPECIAL_N_FLAG_(\w+)\);',
                  lambda m: f'super::set_flag(boma, super::{m[1]});', text)
    text = text.replace('ArticleModule::generate_article(boma, *FIGHTER_BRAVE_GENERATE_ARTICLE_FIREBALL, false, -1);',
                        'super::generate(boma);')
    text = re.sub(r'LAST_EFFECT_SET_WORK_INT\(agent, (WEAPON_\w+)\)', r'LAST_EFFECT_SET_WORK_INT(agent, *\1)', text)
    text = text.replace('SET_TAKEOUT_SE(', 'super::takeout_se(')
    text = text.replace('LAST_EFFECT_SET_WORK_INT(', 'super::effect_work_int(')
    assert 'FIGHTER_BRAVE_' not in text, name
    assert text.count('{') == text.count('}'), name
    return text


def generate():
    pin = json.loads((ROOT / 'refs/brave_special_n/acmd_pin.json').read_text())
    # audit_hero_neutral_b independently verifies file hashes against SOURCE.
    assert pin['commit'] == '59004685238a3f6f93bae905d3a4e079701c40b4'
    parts = ['// Generated by tools/gen_hero_neutral_b_acmd.py v1.0.0; do not edit.',
             'use smash::{app::{lua_bind::*, sv_animcmd::{frame, wait}}, lib::lua_const::*, lua2cpp::*, phx::*};',
             'use smash_script::{*, macros::*};', 'use smashline::*;']
    fighter, weapon = [], []
    provenance = []
    for folder, names in [('brave', ['SpecialNStart', 'SpecialNHold', 'SpecialNCancel',
                         'SpecialAirNStart', 'SpecialAirNHold', 'SpecialAirNCancel',
                         'SpecialN1', 'SpecialN2', 'SpecialN3', 'SpecialAirN1', 'SpecialAirN2', 'SpecialAirN3',
                         'SpecialNHoldM', 'SpecialNHoldMax']),
                         ('brave_fireball', ['SpecialN1', 'SpecialN2', 'SpecialN3', 'BurstS', 'BurstM', 'BurstL'])]:
        for stem in names:
            path = DONOR / folder / (stem + '.txt')
            text = path.read_text()
            provenance.append({'path': path.relative_to(ROOT).as_posix(),
                               'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
            for name, body in split_functions(text).items():
                is_weapon = folder == 'brave_fireball'
                if not is_weapon and name.startswith('sound_') and re.search(r'n[123]$', name):
                    level = name[-1]
                    variants = []
                    for suffix in ('Default', 'usen'):
                        variant = DONOR / folder / f'SpecialN{level}{suffix}.txt'
                        if not any(p['path'] == variant.relative_to(ROOT).as_posix() for p in provenance):
                            provenance.append({'path': variant.relative_to(ROOT).as_posix(),
                                               'sha256': hashlib.sha256(variant.read_bytes()).hexdigest()})
                        local = variant.read_text()
                        local = next(iter(split_functions(local).values()))
                        variants.append(close_prefix(local.split('else {', 1)[0]))
                    body = variants[0]
                    body = re.sub(r'fn sound_\w+\(', f'fn {name}(', body, count=1)
                    body = body.replace(f'PLAY_SEQUENCE(agent, Hash40::new("seq_brave_rnd_special_n{level}_jp"));',
                                        f'let sequence = super::voice_sequence(agent, {level}); PLAY_SEQUENCE(agent, sequence);')
                    # The localized scripts must differ only in their sequence.
                    def normalized(s):
                        s = re.sub(r'fn sound_\w+', 'fn normalized', s)
                        return s.replace('_jp"', '_en"')
                    assert normalized(variants[0]) == normalized(variants[1]), stem
                body = translate(name, body, is_weapon)
                owned_fn = ('weapon_' if is_weapon else '') + name
                body = body.replace('fn ' + name + '(', 'pub(super) unsafe extern "C" fn ' + owned_fn + '(', 1)
                body = body.replace('unsafe extern "C" pub(super) unsafe extern "C"', 'pub(super) unsafe extern "C"')
                parts.append(body)
                cat, suffix = name.split('_', 1)
                script = name if is_weapon else cat + '_pgwrhero' + suffix
                (weapon if is_weapon else fighter).append((cat, script, owned_fn))
    parts.append('pub(super) fn install() {')
    for agent, registrations, gate in [('elight', fighter, True), ('elight_pgwr_hero_fireball', weapon, False)]:
        parts.append(f'    let mut agent = Agent::new("{agent}");')
        if gate:
            parts.append('    agent.set_costume(crate::TARGET_COSTUMES.to_vec());')
        for cat, script, fn in registrations:
            parts.append(f'    agent.{cat}_acmd("{script}", {fn}, Priority::Low);')
        parts.append('    agent.install();')
    parts.append('}')
    return '\n'.join(parts) + '\n', provenance


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source, provenance = generate()
    record = ROOT / 'refs/brave_special_n/acmd_translation.json'
    files = {OUT: source, record: json.dumps({'version': '1.0.0', 'evidence_tier': 'B',
             'inputs': provenance, 'hardware_validated': False}, indent=2) + '\n'}
    for path, content in files.items():
        if args.check:
            assert path.read_text() == content, path
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print('PASS: donor scripts translated, owned fighter flags, localized success branches, balanced syntax')


if __name__ == '__main__':
    main()
