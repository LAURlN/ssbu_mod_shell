"""Generate owned successful fighter side-B game ACMD (v1.0.0).

Requires native hitbox audit equality before accepting the text arguments.
S1's misplaced failure else is removed and its common frame-12 cleanup retained;
the successful path is unconditional. S2/S32 use native-checked arguments.
Ground/air game bodies normalize identically; both registrations use one body.
--check compares generated source; no build, assets, package or install occurs.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import re
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'tools'), str(ROOT / 'src/pgwr/tools')]
from gen_acmd import split_functions
from audit_hero_side_b_hitboxes import generate as native_hitboxes
from audit_hero_side_b_acmd import generate as native_registrations


def normalized(body):
    return re.sub(r'\s+', '', re.sub(r'fn game_special(?:air)?s', 'fn game_specials', body))


def generate():
    native_hitboxes()
    registrations = native_registrations()['registrations']
    s3 = [r for r in registrations if r['script'] in ('game_specials3', 'game_specialairs3')]
    assert len(s3) == 2 and {r['implementation'] for r in s3} == {'0x115590'}
    cfg = tomllib.loads((ROOT / 'paths.toml').read_text())
    donor = ROOT / cfg['dumps']['scripts'] / 'smashline-hdr/lua2cpp_brave/brave'
    parts = ['// Generated by tools/gen_hero_side_b_game_acmd.py v1.0.0.',
             '// Hitboxes checked against pinned native implementations, not trusted from dump alone.',
             'use smash::{app::{lua_bind::*, sv_animcmd::{frame, wait}}, lib::lua_const::*, lua2cpp::*, phx::*};',
             'use smash_script::{*, macros::*};', 'use smashline::*;']
    for phase in ('1', '2', '32'):
        name = 'game_specials' + phase
        body = split_functions((donor / ('SpecialS' + phase + '.txt')).read_text())[name]
        airborne = split_functions((donor / ('SpecialAirS' + phase + '.txt')).read_text())['game_specialairs' + phase]
        assert normalized(body) == normalized(airborne), phase
        if phase == '1':
            assert body.count('else {') == 1
            prefix, failure = body.split('else {', 1)
            marker = 'frame(lua_state, 12.0);'
            assert failure.count(marker) == 1
            body = prefix + marker + failure.split(marker, 1)[1]
            assert body.count('ATTACK(agent,') == 5
        body = body.replace('let boma = agent.boma();', 'let boma = agent.module_accessor;')
        body = body.replace('WorkModule::is_flag(boma, *FIGHTER_BRAVE_STATUS_SPECIAL_S_FLAG_SUCCESS_SP)', 'true')
        body = body.replace('WorkModule::on_flag(boma, *FIGHTER_BRAVE_STATUS_SPECIAL_S_FLAG_ENABLE_SPARK);',
            'if let Some(state) = super::state::get(boma) { state.set(super::state::ENABLE_SPARK); }')
        assert 'FIGHTER_BRAVE_' not in body and body.count('{') == body.count('}')
        body = body.replace('unsafe extern "C" fn ' + name,
                            'pub(super) unsafe extern "C" fn game_' + phase, 1)
        parts.append(body)
    parts.append('pub(super) fn install() {\n    let mut agent = Agent::new("elight");\n'
                 '    agent.set_costume(crate::TARGET_COSTUMES.to_vec());')
    for air in ('', 'air'):
        for phase in ('1', '2', '32'):
            parts.append(f'    agent.game_acmd("game_pgwrherospecial{air}s{phase}", game_{phase}, Priority::Low);')
        parts.append(f'    agent.game_acmd("game_pgwrherospecial{air}s3", super::attack3_acmd::game, Priority::Low);')
    parts.append('    agent.install();\n}')
    return '\n'.join(parts) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate()
    path = ROOT / 'src/pgwr/plugin/src/mythra/hero_side_b/game_acmd.rs'
    if args.check: assert path.read_text() == text, 'stale game ACMD'
    else: path.write_text(text)
    print('PASS: native-checked S1/S2/S32 game ACMD, unconditional success, identical air pairs, owned state; source only')


if __name__ == '__main__': main()
