"""Generate owned Monkey Flip capture offsets and 13.0.4 signature guards (1.0.0).

Usage: toolchains/py312/python.exe tools/gen_mflip_capture_data.py [--check]
Smoke test: generate then --check. Reads dumps through paths.toml. Copies the
common thrown-parameter Diddy offset table by fighter-kind hash, not row number.
Pinned skyline-smash 315e4e8 supplies fighter kinds. No runtime donor calls.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'tools'), str(ROOT / 'src/pgwr/tools')]
from main_image import MainImage
import prc


def generate():
    cfg = tomllib.loads((ROOT / 'paths.toml').read_text())
    path = ROOT / cfg['dumps']['arc'] / 'fighter/common/param/fighter_param_thrown.prc'
    constants = next((Path.home() / '.cargo/git/checkouts').glob(
        'skyline-smash-*/315e4e8/src/lua_const.rs'))
    kinds = {prc.hash40('fighter_kind_' + name.lower()): (name, int(value, 16))
             for name, value in re.findall(r'FIGHTER_KIND_([A-Z0-9_]+): (0x[0-9A-Fa-f]+),', constants.read_text())}
    tree = prc.as_dict(prc.read(path))
    offsets = tree[prc.hash40('diddy_special_s')][1]
    rows = tree[prc.hash40('fighter_param_thrown_table')][1]
    assert len(offsets) == 3 * len(rows) == 282
    records = []
    for index, row in enumerate(rows):
        kind_hash = prc.as_dict(row)[prc.hash40('fighter_kind')][1]
        name, kind = kinds[kind_hash]
        values = offsets[index * 3:index * 3 + 3]
        assert all(tag == 'float' for tag, value in values)
        records.append({'name': name, 'kind': kind, 'row': index,
                        'offset': [value for tag, value in values]})
    assert len({r['kind'] for r in records}) == 94
    img = MainImage()
    lines = ['// Generated by tools/gen_mflip_capture_data.py 1.0.0; do not edit.',
             '// Source hashes: refs/diddy_monkey_flip/capture_owned_data.json',
             'pub fn offset(kind: i32) -> Option<[f32; 3]> {', '    match kind {']
    for r in sorted(records, key=lambda r: r['kind']):
        lines.append(f"        {r['kind']} => Some([{', '.join(repr(v) + 'f32' for v in r['offset'])}]), // {r['name']}")
    lines += ['        _ => None,', '    }', '}']
    for name, start, end in [('PYRA_HANDLER', 0xA0C8D0, 0xA0CC14),
                             ('DIDDY_HANDLER', 0x956B70, 0x9570A0)]:
        raw = img.data[start:end]
        lines.append(f'pub const {name}: &[u8] = &[')
        lines += ['    ' + ', '.join(f'0x{v:02x}' for v in raw[i:i+16]) + ',' for i in range(0, len(raw), 16)]
        lines.append('];')
    report = {'date': '2026-09-30', 'tier': 'B', 'tool_version': '1.0.0',
              'tool': 'tools/gen_mflip_capture_data.py',
              'tool_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
              'input': path.relative_to(ROOT).as_posix(),
              'input_sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
              'kind_source': {'repo': 'https://github.com/ultimate-research/skyline-smash',
                              'commit': '315e4e8bebb460ebb9f02f30f07b0f13883ba3d6',
                              'file': 'src/lua_const.rs',
                              'sha256': hashlib.sha256(constants.read_bytes()).hexdigest()},
              'main_sha256': hashlib.sha256(img.data).hexdigest(),
              'nana_alias': 'native helper maps 0x4c to 0x4b (Popo)',
              'records': records,
              'limitation': 'Copied data/signatures only; behavior awaits console controls.'}
    return {ROOT / 'src/pgwr/plugin/src/status/monkey_flip_capture_data.rs': '\n'.join(lines) + '\n',
            ROOT / 'refs/diddy_monkey_flip/capture_owned_data.json': json.dumps(report, indent=2) + '\n'}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    for path, content in generate().items():
        if args.check:
            assert path.read_text() == content, path.relative_to(ROOT)
        else:
            path.write_text(content, encoding='utf-8')
    print('PASS: 94 owned capture offsets and complete handler signatures')


if __name__ == '__main__':
    main()
