"""Audit the authorized 13.0.4 Snake grenade life bridge and pin/throw path (v1.1.0).

Read-only dump inspection; --check is the smoke test. Pins the entire leaf
function and manager offsets. Offline evidence only, never a runtime verdict.
"""
import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from main_image import MainImage, ROOT
from maindesc import descriptors

OFFSET = 0x1674e90
EXPECTED = bytes.fromhex('28e201f008d941f908f143f9087940f9000140b9c0035fd6')

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    image = MainImage()
    assert hashlib.sha256(image.data).hexdigest() == 'f70c97d2bdcd00c2e81559f5abd0871e3c550b240d2005ab2e6085957a9d7613'
    assert image.data[OFFSET:OFFSET + len(EXPECTED)] == EXPECTED
    assert image.function_text(OFFSET) == ['adrp x8, #0x52bb000', 'ldr x8, [x8, #0x3b0]',
        'ldr x8, [x8, #0x7e0]', 'ldr x8, [x8, #0xf0]', 'ldr w0, [x8]', 'ret']
    pin = descriptors(image, 0x22)[12]
    assert pin == {'index': 12, 'weapon_kind': 0x199, 'max': 2, 'init': 0x11b71c0, 'fini': 0, 'extra': 0}
    pin_code = image.disasm(pin['init'], 0x158)
    assert pin_code[-1].mnemonic == 'ret'
    assert not any(ins.mnemonic == 'adrp' and '#0x52bb000' in ins.op_str for ins in pin_code)
    symbols_path = ROOT / 'dumps/decoded/main_symbols.json'
    symbols = {s['name']: s for s in json.loads(symbols_path.read_text())}
    exported = {}
    for name, expected in {
        '_ZN3app8lua_bind31Item__item_module_accessor_implEPNS_4ItemE': ['add x0, x0, #0x98', 'ret'],
        '_ZN3app8lua_bind23Item__throw_attack_implEPNS_4ItemEfRKN3phx8Vector3fEf': ['mov w2, wzr', 'b #0x15aba90'],
        '_ZN3app8lua_bind31AttackModule__set_power_up_implEPNS_26BattleObjectModuleAccessorEf':
            ['ldr x0, [x0, #0xa0]', 'ldr x8, [x0]', 'ldr x1, [x8, #0x460]', 'br x1'],
    }.items():
        symbol = symbols[name]
        assert image.function_text(symbol['address']) == expected
        exported[name] = {'offset': symbol['address'], 'instructions': expected}
    log_name = '_ZN3app7sv_item22update_log_attack_infoEPNS_4ItemEi'
    log_symbol = symbols[log_name]
    log_code = image.disasm(log_symbol['address'], log_symbol['size'])
    # The public generic helper uses the donor shoot callback's same stale-log
    # row lookup and Item vtable +0x588 dispatch, without calling Snake code.
    assert any(i.op_str == 'x8, [x8, #0x588]' for i in log_code)
    assert any(i.op_str == 'w9, #0x14' for i in log_code)
    exported[log_name] = {'offset': log_symbol['address'], 'size': log_symbol['size'],
                         'signature_sha256': hashlib.sha256(image.data[log_symbol['address']:log_symbol['address']+log_symbol['size']]).hexdigest()}
    shoot = image.disasm(0x11b6da0, 0x420)
    assert any(i.op_str == 'x8, [x8, #0x588]' for i in shoot)
    assert any(i.op_str == 'x8, [x8, #0x460]' for i in shoot)
    record = {'tool_version': '1.1.0', 'date': '2026-09-30', 'evidence_tier': 'B',
        'hardware_validated': False, 'input': image.path.relative_to(ROOT).as_posix(),
        'sha256': hashlib.sha256(image.data).hexdigest(), 'offset': OFFSET,
        'signature': EXPECTED.hex(), 'instructions': image.function_text(OFFSET),
        'scope': 'Original life when Snake parameter slot exists; owned 150 otherwise',
        'authorization': 'projects/pgwr/TODO.md: route A decision 2026-09-30',
        'pin_descriptor': pin, 'pin_init_sha256': hashlib.sha256(image.data[0x11b71c0:0x11b7318]).hexdigest(),
        'pin_param_manager_reads': [], 'exported_generic_helpers': exported,
        'symbols_input': symbols_path.relative_to(ROOT).as_posix(), 'symbols_sha256': hashlib.sha256(symbols_path.read_bytes()).hexdigest()}
    path = ROOT / 'refs/snake_grenade/life_native.json'
    content = json.dumps(record, indent=2) + '\n'
    signatures = [(OFFSET, EXPECTED), (0x11b71c0, image.data[0x11b71c0:0x11b7318])]
    signatures += [(symbol['address'], image.data[symbol['address']:symbol['address']+symbol['size']])
                   for symbol in [symbols[name] for name in exported]]
    rust = '// Generated by tools/audit_snake_grenade_native.py v1.1.0; do not edit.\n'
    rust += 'pub const SIGNATURES: &[(usize, &[u8])] = &[\n'
    for offset, data in signatures:
        rust += f'    (0x{offset:x}, &[{", ".join(f"0x{byte:02x}" for byte in data)}]),\n'
    rust += '];\n'
    rust_path = ROOT / 'src/pgwr/plugin/src/status/snake_grenade/native_signatures.rs'
    for dest, text in ((path, content), (rust_path, rust)):
        if args.check:
            assert dest.read_text() == text
        else:
            dest.write_text(text)
    print('PASS: full life/pin signatures and exported throw/log/power-up helpers')

if __name__ == '__main__':
    main()
