"""Translate pinned cargo callbacks into task-owned ARM64, never donor calls.

Usage: python -B src/pgwr/tools/dk_cargo/emit_callbacks.py
Fails on unclassified address operands, indirect calls, missing constants or
donor imports. Generated code requires the task runtime adapters and is not
registered by this tool. Branch labels preserve instruction identity; relocated
data, status IDs, work flag, motion hashes and parameter imports are owned.
"""
import json
import re
import struct
from pathlib import Path
from audit import ROOT, OUT, sha, write
from closure import image

DEST = ROOT / 'src/pgwr/plugin/src/status/dk_cargo'
ROLES = ['SHOULDER_START', 'SHOULDER_WAIT', 'SHOULDER_WALK', 'SHOULDER_TURN',
         'SHOULDER_JUMP_SQUAT', 'SHOULDER_JUMP_SQUAT_B', 'SHOULDER_JUMP',
         'SHOULDER_FALL', 'SHOULDER_LANDING', 'SHOULDER_PASS', 'SHOULDER_END',
         'THROW_F_F', 'THROW_F_B', 'THROW_F_HI', 'THROW_F_LW']
OWN_CONST = {'FIGHTER_DONKEY_STATUS_KIND_' + n: i for i,n in enumerate(ROLES)}
OWN_CONST.update({'FIGHTER_STATUS_KIND_SHOULDERED_DONKEY_START': 15,
                  'FIGHTER_STATUS_KIND_SHOULDERED_DONKEY': 16,
                  'FIGHTER_STATUS_KIND_SHOULDERED_DONKEY_THROWN': 17})
FLAG = 'FIGHTER_DONKEY_STATUS_SHOULDER_START_FLAG_SHOULDER_WAIT'
# Engine shoulder_throw queues the named stock victim state before owned Pre
# routing. End/Exit must recognize that transient identity without cutting the
# capture. Scope the semantic alias comparison to these three cleanup sites.
CLEANUP_EQ_SITES = {0x25c748, 0x25dd2c, 0x25dd64}
ADAPTERS = {
 '_ZN3app25FighterSpecializer_Donkey16apply_lift_paramERNS_21FighterModuleAccessorEb': 'pgwr_dkc_lift',
 '_ZN3lib8L2CValueC1EN3phx6Hash40E': 'pgwr_dkc_hash_value',
 '_ZN3app8lua_bind24WorkModule__is_flag_implEPNS_26BattleObjectModuleAccessorEi': 'pgwr_dkc_is_flag',
 '_ZN3app8lua_bind24WorkModule__on_flag_implEPNS_26BattleObjectModuleAccessorEi': 'pgwr_dkc_on_flag',
 '_ZN3app8lua_bind25WorkModule__off_flag_implEPNS_26BattleObjectModuleAccessorEi': 'pgwr_dkc_off_flag',
 '_ZN3app8lua_bind30WorkModule__get_param_int_implEPNS_26BattleObjectModuleAccessorEmm': 'pgwr_dkc_param_int',
 '_ZN3app8lua_bind32WorkModule__get_param_float_implEPNS_26BattleObjectModuleAccessorEmm': 'pgwr_dkc_param_float',
 '_ZN3app8lua_bind48FighterParamAccessor2__donkey_thrown_offset_implEPNS_21FighterParamAccessor2Eii': 'pgwr_dkc_thrown_offset',
}

def label(kind, addr): return f'pgwr_dkc_{kind}_{addr:x}'

def run():
    graph = json.loads((OUT/'callback_closure.json').read_text())
    annotations = json.loads((OUT/'semantic_annotations.json').read_text())
    annotated = {k: {int(a['at'],0): a['labels'] for f in v['functions'] for a in f['annotations']}
                 for k,v in annotations['images'].items()}
    sources = {k: image(k) for k in graph['images']}
    exported = {f['symbol']: label(k,int(f['entry'],0))
                for k,x in graph['images'].items() for f in x['functions'] if f['symbol']}
    # Resolve the full constant-bank symbol vocabulary from pinned name hashes.
    ns = {'__file__': str(ROOT/'tools/constmap.py')}
    exec((ROOT/'tools/constmap.py').read_text().split('d=NRO_PATH.read_bytes()')[0], ns)
    names = re.findall(r'^\s+([A-Z_0-9a-z]+): ', (OUT/'lua_const.rs').read_text(), re.M)
    reverse = {ns['xxh64'](n.encode()): n for n in names}
    constants = {o*4: reverse.get(struct.unpack_from('<Q',sources['common'][1],0x6a5b70+o*8)[0])
                 for o in range(0x4c0d)}
    output = ['// Generated by emit_callbacks.py; no donor NRO addresses.',
              '.section .text.pgwr_dkc_callbacks,"ax",%progbits', '.p2align 2']
    # These allocation literals are defined in our Rust object. Hide them from
    # ELF interposition so their ADRP/LO12 references are valid PIC relocations.
    output.extend(f'.hidden pgwr_dkc_id_{i}' for i in range(19))
    report, relocations, imported = [], [], set()
    all_ins = {}
    for kind, x in graph['images'].items():
        _,raw,data,meta,labels,imports,slots = sources[kind]
        assert sha(raw) == x['sha256']
        for f in x['functions']:
            assert not f['indirect_calls'], (kind,f['entry'])
            path = OUT/f['asm']
            assert sha(path.read_bytes()) == f['asm_sha256']
            for line in path.read_text().splitlines():
                a, code = line.split(':',1)
                a=int(a,0); code=code.strip()
                if (kind,a) in all_ins: assert all_ins[kind,a] == code
                all_ins[kind,a] = code
    # One section per image, every original instruction address is a label.
    for kind,x in graph['images'].items():
        _,raw,data,meta,labels,imports,slots = sources[kind]
        functions = {int(f['entry'],0) for f in x['functions']}
        pointers = {int(p['at'],0): int(p['target'],0) for f in x['functions'] for p in f['function_pointers']}
        reads = {int(r['at'],0): r for f in x['functions'] for r in f['data_reads']}
        pages, tables = {}, set()
        replacements = {}
        # Classify PC-relative operands before emitting anything. Constant-bank
        # loads use the generic exported table; DK state/flag loads are replaced
        # independently with our allocation. No donor numeric IDs survive.
        for a,code in sorted((a,c) for (k,a),c in all_ins.items() if k==kind):
            if a in functions:
                pages.clear()
                tables.clear()
            m,_,ops=code.partition(' '); ops=ops.strip()
            if m=='adrp':
                reg,val=ops.split(', #'); pages[reg]=(a,int(val,0))
            elif a in pointers:
                mm=re.fullmatch(r'(x\d+), (x\d+), #(0x[0-9a-f]+|\d+)',ops)
                assert mm and mm[2] in pages,(kind,hex(a),code)
                origin,_=pages[mm[2]]; target=label(kind,pointers[a])
                replacements[origin]=f'adrp {mm[2]}, {target}'
                replacements[a]=f'add {mm[1]}, {mm[2]}, :lo12:{target}'
                relocations.append({'image':kind,'at':hex(a),'kind':'owned callback pointer','target':target})
            elif a in reads:
                r=reads[a]
                mm=re.fullmatch(r'([xwsdq]\d+), \[(x\d+), #(0x[0-9a-f]+|\d+)\]',ops)
                assert mm and mm[2] in pages,(kind,hex(a),code)
                origin,_=pages[mm[2]]; address=int(r['address'],0)
                symbol=r['import']
                if symbol=='_ZN7lua2cpp21L2CAgentGeneratedBase19const_value_table__E' or (kind=='common' and address==0x80b578):
                    target='_ZN7lua2cpp21L2CAgentGeneratedBase19const_value_table__E'
                    # GOT contains the address of the exported table itself.
                    replacements[origin]=f'adrp {mm[2]}, :got:{target}'
                    replacements[a]=f'ldr {mm[1]}, [{mm[2]}, :got_lo12:{target}]'
                    tables.add(mm[1]); imported.add(target)
                elif symbol:
                    assert symbol in ('_ZN3lib8L2CValue3NILE', '_ZN3lib9SingletonIN3app21FighterParamAccessor2EE9instance_E'),symbol
                    replacements[origin]=f'adrp {mm[2]}, :got:{symbol}'
                    replacements[a]=f'ldr {mm[1]}, [{mm[2]}, :got_lo12:{symbol}]'
                    imported.add(symbol)
                else:
                    if r['width']==8:
                        # Native GOT callback pointers become direct owned
                        # ADRP/ADD addresses: no absolute relocation in text.
                        value=struct.unpack_from('<Q',data,address)[0]
                        assert (kind,value) in all_ins,(kind,hex(address),hex(value))
                        target=label(kind,value)
                        replacements[origin]=f'adrp {mm[2]}, {target}'
                        replacements[a]=f'add {mm[1]}, {mm[2]}, :lo12:{target}'
                    else:
                        target=f'pgwr_dkc_data_{kind}_{address:x}'
                        replacements[origin]=f'adrp {mm[2]}, {target}'
                        replacements[a]=f'ldr {mm[1]}, [{mm[2]}, :lo12:{target}]'
                relocations.append({'image':kind,'at':hex(a),'kind':'classified data','source':r})
            elif m=='ldr':
                mm=re.fullmatch(r'(w\d+), \[(x\d+), #(0x[0-9a-f]+|\d+)\]',ops)
                if mm and mm[2] in tables:
                    symbol=constants[int(mm[3],0)]
                    assert symbol,(kind,hex(a),code)
                    old=[n for n in annotated[kind].get(a,[]) if n==symbol]
                    # The older annotation pass loses some long-lived table
                    # registers. The independently decoded XXH64 bank is the
                    # authoritative symbol, rather than an annotation guess.
                    if symbol in OWN_CONST or symbol==FLAG:
                        index=OWN_CONST.get(symbol,18)
                        target=f'pgwr_dkc_id_{index}'
                        # A scratch register is unavailable here. Use the
                        # destination's X view for ADRP, then load its W view.
                        xreg='x'+mm[1][1:]
                        replacements[a]=f'adrp {xreg}, {target}\nldr {mm[1]}, [{xreg}, :lo12:{target}]'
                        relocations.append({'image':kind,'at':hex(a),'kind':'owned ID','symbol':symbol,'index':index})
                    elif 'DONKEY' in symbol and not symbol.startswith('FIGHTER_STATUS_SHOULDERED_DONKEY_WORK_'):
                        raise AssertionError(('unowned DK constant',kind,hex(a),symbol))
        for a,code in sorted((a,c) for (k,a),c in all_ins.items() if k==kind):
            m,_,ops=code.partition(' '); ops=ops.strip()
            here=label(kind,a)
            if a in functions:
                output.extend([f'.global {here}',f'.hidden {here}', f'.type {here},%function'])
            output.append(here+':')
            if a in replacements:
                output.append(replacements[a]); continue
            if m in ('b','bl') or m.startswith('b.') or m in ('cbz','cbnz','tbz','tbnz'):
                match=re.search(r'#(0x[0-9a-f]+|\d+)$',ops); assert match,(kind,hex(a),code)
                target=int(match[1],0)
                if target in imports:
                    symbol=imports[target]
                    destination=ADAPTERS.get(symbol, exported.get(symbol,symbol))
                    if kind=='common' and a in CLEANUP_EQ_SITES:
                        assert m=='bl' and symbol=='_ZNK3lib8L2CValueeqERKS0_'
                        destination='pgwr_dkc_cleanup_status_eq'
                        relocations.append({'image':kind,'at':hex(a),'kind':'queued stock/owned cleanup alias','target':destination})
                    assert 'FighterSpecializer_' not in destination
                    assert not ('Donkey' in destination or 'donkey' in destination), (symbol,destination)
                    if destination==symbol: imported.add(symbol)
                else:
                    assert (kind,target) in all_ins,(kind,hex(a),hex(target))
                    destination=label(kind,target)
                output.append(m+' '+ops[:match.start()]+destination)
            else:
                assert m not in ('adr','adrp','blr','br'), (kind,hex(a),code,'unclassified relocation')
                output.append(code)
        for address in sorted({int(r['address'],0) for r in reads.values() if not r['import'] and not (kind=='common' and r['address']=='0x80b578')}):
            width=next(r['width'] for r in reads.values() if int(r['address'],0)==address)
            if width==8:
                continue
            else:
                assert width==4
                output.extend(['.p2align 3',f'pgwr_dkc_data_{kind}_{address:x}:'])
                output.append('.word '+hex(struct.unpack_from('<I',data,address)[0]))
        report.append({'image':kind,'source_sha256':sha(raw),'functions':len(functions),
                       'instructions':sum(k==kind for k,a in all_ins)})
    DEST.mkdir(exist_ok=True)
    asm='\n'.join(output)+'\n'
    (DEST/'callbacks.S').write_text(asm,encoding='utf-8')
    write('callback_translation.json', {'tier':'B','runtime_verified':False,
          'generator_sha256':sha(Path(__file__).read_bytes()),'asm_sha256':sha(asm.encode()),
          'images':report,'relocations':relocations,'generic_imports':sorted(imported),
          'adapters':ADAPTERS,'role_indices':OWN_CONST,'donor_code_called':False,
          'ready':False,'limitation':'Assembly translation is an offline check, not capture/release verification.'})
    print('PASS:',len(all_ins),'instructions translated;',len(relocations),'owned/classified relocations; no donor imports')

if __name__=='__main__': run()
