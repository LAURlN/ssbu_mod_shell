"""Retarget Diddy's twelve Monkey Flip clips onto the G&W model and describe the
motion-list entries the port needs.

Used by ``build.py``'s ``build_motion`` step, which owns the motion list and the
clip folder for Pyra c06/c07. This module does not write a motion list of its
own: it returns the donor's entries and a writer for one clip, and the caller
folds them into the list it is already building. That is the same shape
``build_cloud_fair.py`` uses for Pyra's forward air, and it is what keeps the
"every referenced clip is one we wrote" assertion in ``build_motion`` true.

# Why the retarget is imported, not reimplemented

``src/mgw_swap/tools/build_monkey_flip_assets.py`` already does this retarget for
the frozen swap project, and the parts that matter there are the parts that were
debugged: dropping donor transform tracks by bone-name intersection (Diddy has 84
transform tracks, G&W's skeleton binds 37 of those names), replacing the donor's
Visibility and Material groups with G&W's own, and pinning G&W's visibility layout
by hash so a changed source motion fails the build. This module imports that
file's helpers rather than copying them, for the same reason
``build_hero_spin.py`` imports the donor's: a copy can drift from the version the
donor validated.

What is different here, and therefore implemented locally:

* the recipient is the **grafted** eflame c06/c07 model, whose skeleton is G&W's
  plus Pyra's bones, so the bone set is read per slot from the G&W export the
  model was built from;
* the visibility source is the recipient slot's own idle clip
  (``gamewatch/motion/body/<slot>/a00wait1.nuanmb``), validated against the
  donor's pinned layout id, rather than a hard-coded c00 path. The swap project
  only ever built c07; this builds both slots, and the two slots' idles are worth
  checking rather than assuming;
* the **output file name is the caller's**, because this project may not add clip
  file names: ``build_motion`` aliases every donor clip name the base install
  does not have onto a spare eflame name, and the retargeted clip is written under
  that name.

# Why the twelve slots need their own clips

Each of the donor's twelve statuses names its own animation, and eight of the
twelve are body-distinct (the donor's own audit fingerprints them). Two clips
sharing a file would make two phases play the same animation, so the caller
asserts that the twelve slots end up on twelve distinct target names.

Run: nothing. This is a library import for ``build.py``; ``build.py`` prints the
per-clip report.
"""
from __future__ import annotations

import hashlib
import os
import struct
import sys
import zlib
from pathlib import Path

import ssbh_data_py as s

TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parents[2]
EXPORT = Path(os.environ.get('MGW_EXPORT', ROOT / 'dumps' / 'arc'))

# The donor project's helpers. Absolute path into the sibling project rather than
# a relative one, because that is where they live and this folder is not
# regenerated by anything.
SWAP_TOOLS = ROOT / 'src' / 'mgw_swap' / 'tools'
sys.path.insert(0, str(SWAP_TOOLS))
sys.path.insert(0, str(SWAP_TOOLS / 'vendor'))

import build_monkey_flip_assets as _donor  # noqa: E402  (the donor's retarget helpers)

DONOR_DIR = EXPORT / 'fighter' / 'diddy' / 'motion' / 'body' / 'c00'
DONOR_MLIST = DONOR_DIR / 'motion_list.bin'

# (motion kind, donor clip) in the donor's move order, from the donor project's
# own audit (`motion_list.yml` lines 3064-3423).
MOTIONS = (
    ('special_s_start', 'd01specialsstart.nuanmb'),
    ('special_air_s_start', 'd01specialairsstart.nuanmb'),
    ('special_air_s_jump', 'd01specialairsjump.nuanmb'),
    ('special_air_s_kick', 'd01specialairskick.nuanmb'),
    ('special_s_kick_landing', 'd01specialskicklanding.nuanmb'),
    ('special_air_s_fall', 'd01specialairsfall.nuanmb'),
    ('special_s_stick', 'd01specialsstick.nuanmb'),
    ('special_s_stick_attack', 'd01specialsstickattack.nuanmb'),
    ('special_s_stick_attack2', 'd01specialsstickattack2.nuanmb'),
    ('special_s_stick_jump', 'd01specialsstickjump.nuanmb'),
    ('special_s_stick_jump2', 'd01specialsstickjump2.nuanmb'),
    ('special_s_landing', 'd01specialslanding.nuanmb'),
)

# Cancel frames, from the donor's motion list. Non-zero values are asserted; a
# zero is asserted to be none-or-zero, because a `size % 8 == 0` entry has no
# cancel field at all.
EXPECTED_CANCEL = {
    'special_s_start': 0,
    'special_air_s_start': 0,
    'special_air_s_jump': 0,
    'special_air_s_kick': 33,
    'special_s_kick_landing': 19,
    'special_air_s_fall': 0,
    'special_s_stick': 0,
    'special_s_stick_attack': 0,
    'special_s_stick_attack2': 17,
    'special_s_stick_jump': 0,
    'special_s_stick_jump2': 17,
    'special_s_landing': 27,
}

# The donor's shape, re-checked every run so a dump or recipient change fails the
# build instead of shipping a wrong pose.
EXPECTED_DONOR_TRANSFORM_TRACKS = _donor.EXPECTED_DONOR_TRANSFORM_TRACKS
EXPECTED_KEPT_TRACKS = _donor.EXPECTED_KEPT_TRACKS
EXPECTED_VIS_NODES = _donor.EXPECTED_VIS_NODES
EXPECTED_VIS_LAYOUT = _donor.GW_VIS_LAYOUT
EXPECTED_VIS_VISIBLE = _donor.EXPECTED_VIS_VISIBLE


def hash40(name: str) -> int:
    data = name.encode('utf-8')
    return (len(data) << 32) | zlib.crc32(data)


def motion_kinds() -> set:
    """The twelve motion kinds, as hashes, for the caller's overlap check."""
    return {hash40(kind) for kind, _ in MOTIONS}


def donor_clips() -> dict:
    """Donor clip-name hash -> path, for the twelve clips these slots name."""
    clips = {}
    for _, clip in MOTIONS:
        path = DONOR_DIR / clip
        if not path.is_file():
            raise SystemExit(f'monkey flip: missing donor clip {path}')
        clips[hash40(clip)] = path
    return clips


def donor_entries() -> dict:
    """The donor's twelve motion-list entries, validated, keyed by kind hash.

    Each entry is copied whole - kind, game script, flags, blend, cancel frame and
    the entry's own tail - exactly as the donor's list has it, because an entry
    carries more than its clip names and the only way to reproduce the donor's
    timing is to copy the donor's bytes. Only the animation-name field is
    repointed, and the caller does that with the alias map it owns.
    """
    _, _, donor = _donor.parse_mlist(DONOR_MLIST)
    entries = {}
    for kind, clip in MOTIONS:
        key = hash40(kind)
        if key not in donor:
            raise SystemExit(f'monkey flip: donor motion list has no {kind}')
        entry = donor[key]
        expected_script = hash40('game_' + kind.replace('_', ''))
        if entry['game_script'] != expected_script:
            raise SystemExit(
                f'monkey flip: {kind} donor game_script is '
                f'{entry["game_script"]:#x}, expected game_{kind.replace("_", "")} '
                f'({expected_script:#x}); the ported ACMD would not bind')
        if len(entry['animations']) != 1:
            raise SystemExit(
                f'monkey flip: {kind} donor entry has {len(entry["animations"])} '
                f'animations, expected exactly 1')
        if entry['animations'][0] != hash40(clip):
            raise SystemExit(
                f'monkey flip: {kind} donor entry names animation '
                f'{entry["animations"][0]:#x}, expected {clip}')
        want = EXPECTED_CANCEL[kind]
        got = entry['cancel']
        if want and got != want:
            raise SystemExit(
                f'monkey flip: {kind} cancel frame {got}, expected {want}')
        if not want and got not in (None, 0):
            raise SystemExit(
                f'monkey flip: {kind} has cancel frame {got}, expected none/0')
        if struct.unpack_from('<Q', entry['raw'], 24)[0] != hash40(clip):
            raise SystemExit(
                f'monkey flip: {kind} entry does not name {clip} at its animation '
                f'offset, so the alias would land in the wrong field')
        # Normalised to build_motion's own key name (`anims`), so the caller does
        # not have to know which parser produced the entry.
        entries[key] = {'raw': entry['raw'], 'anims': entry['animations']}
    if len(entries) != len(MOTIONS):
        raise SystemExit('monkey flip: motion kinds are not unique')
    return entries


def repoint(entry: dict, target_hash: int) -> dict:
    """One donor entry with its single animation name replaced by `target_hash`."""
    raw = bytearray(entry['raw'])
    struct.pack_into('<Q', raw, 24, target_hash)
    return {'raw': bytes(raw), 'anims': (target_hash,)}


def recipient_bones(gw_slot: str) -> list:
    """The recipient model's bone names, read from the G&W export it was built from.

    The built eflame model is G&W's skeleton with Pyra's bones grafted on
    (`build.py:build_skeleton`), so the bone *names* are a superset of these. The
    retarget intersects the donor's tracks with this set, exactly as the swap
    project did, which is why the count is the donor's measured 37 and not the
    recipient's total.
    """
    path = EXPORT / 'fighter' / 'gamewatch' / 'model' / 'body' / gw_slot / 'model.nusktb'
    if not path.is_file():
        raise SystemExit(f'monkey flip: missing recipient skeleton {path}')
    return [b.name for b in s.skel_data.read_skel(str(path)).bones]


def visibility_group(gw_slot: str):
    """The recipient slot's own idle visibility group, validated and rebuilt.

    G&W has no single canonical visibility layout - the swap project measured 73
    distinct layouts across his 241 c00 motions, because the layout encodes which
    hand mesh and which held item are drawn. The defensible source is therefore the
    recipient's own default standing layout, which is what `a00wait1` carries, and
    it is pinned by layout hash so a changed dump fails here.
    """
    path = EXPORT / 'fighter' / 'gamewatch' / 'motion' / 'body' / gw_slot / 'a00wait1.nuanmb'
    if not path.is_file():
        raise SystemExit(f'monkey flip: missing recipient visibility source {path}')
    anim = s.anim_data.read_anim(str(path))
    group = _donor.groups_by_type(anim).get('Visibility')
    if group is None:
        raise SystemExit(f'monkey flip: no Visibility group in {path}')
    if len(group.nodes) != EXPECTED_VIS_NODES:
        raise SystemExit(
            f'monkey flip: {path.name} has {len(group.nodes)} visibility nodes, '
            f'expected {EXPECTED_VIS_NODES}')
    layout = _donor.visibility_layout_id(group)
    if layout != EXPECTED_VIS_LAYOUT:
        raise SystemExit(
            f'monkey flip: {path.name} visibility layout {layout}, expected '
            f'{EXPECTED_VIS_LAYOUT} (the layout the swap project pinned on the c00 '
            f'idle). The two slots are supposed to share it; if this slot genuinely '
            f'differs, re-derive the pin rather than dropping this check.')
    visible = sorted(n.name for n in group.nodes
                     if all(bool(v) for t in n.tracks for v in (t.values or [])))
    if tuple(visible) != tuple(sorted(EXPECTED_VIS_VISIBLE)):
        raise SystemExit(
            f'monkey flip: {path.name} visible set {visible}, expected '
            f'{sorted(EXPECTED_VIS_VISIBLE)}')
    return group


def retarget(clip_hash: int, clip_path: Path, bones: set, vis_source, out_path: Path) -> dict:
    """Write one retargeted clip to `out_path`, and prove what was written.

    Drops the donor's Visibility and Material groups and installs the recipient's
    visibility group at the clip's own length - G&W's clips carry no Material
    nodes at all, so the recipient's empty material set is the correct one.
    """
    anim = s.anim_data.read_anim(str(clip_path))
    groups = _donor.groups_by_type(anim)
    for required in ('Transform', 'Visibility', 'Material'):
        if required not in groups:
            raise SystemExit(f'monkey flip: {clip_path.name} has no {required} group')

    donor_nodes = list(groups['Transform'].nodes)
    kept = [n for n in donor_nodes if n.name in bones]
    if len(donor_nodes) != EXPECTED_DONOR_TRANSFORM_TRACKS:
        raise SystemExit(
            f'monkey flip: {clip_path.name} has {len(donor_nodes)} transform '
            f'tracks, expected {EXPECTED_DONOR_TRANSFORM_TRACKS}')
    if len(kept) != EXPECTED_KEPT_TRACKS:
        raise SystemExit(
            f'monkey flip: {clip_path.name} keeps {len(kept)} of '
            f'{len(donor_nodes)} transform tracks, expected {EXPECTED_KEPT_TRACKS}. '
            f'The recipient skeleton is not the one this retarget was written '
            f'against; check the grafted bones before trusting the output.')

    frame_count = int(round(anim.final_frame_index)) + 1
    groups['Transform'].nodes = kept
    anim.groups = [groups['Transform'], _donor.build_visibility_group(vis_source, frame_count)]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    anim.save(str(out_path))

    check = s.anim_data.read_anim(str(out_path))
    found = _donor.groups_by_type(check)
    if set(found) != {'Transform', 'Visibility'}:
        raise SystemExit(f'monkey flip: {out_path.name} has groups {sorted(found)}')
    if int(round(check.final_frame_index)) + 1 != frame_count:
        raise SystemExit(f'monkey flip: {out_path.name} frame count changed')
    if [n.name for n in found['Transform'].nodes] != [n.name for n in kept]:
        raise SystemExit(f'monkey flip: {out_path.name} transform bones changed')

    return {
        'clip': clip_path.name,
        'output': out_path.name,
        'frames': frame_count,
        'transform_tracks_in': len(donor_nodes),
        'transform_tracks_kept': len(kept),
        'dropped_tracks': sorted(n.name for n in donor_nodes if n.name not in bones),
        'donor_sha256': _sha256(clip_path),
        'output_sha256': _sha256(out_path),
        'retargeted_fingerprint': _donor.values_fingerprint(kept),
        'donor_fingerprint': _donor.values_fingerprint(donor_nodes),
    }


def _sha256(path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def assert_distinct(records: list) -> None:
    """Two phases must not play the same animation because of the retarget.

    Raw inequality is the wrong test: two donor motions that are already identical
    across all 84 tracks are allowed to stay identical, because the drop did not
    cause that. What is forbidden is the drop discarding the only difference
    between two donor-distinct motions.
    """
    by_fingerprint = {}
    for rec in records:
        by_fingerprint.setdefault(rec['retargeted_fingerprint'], []).append(rec)
    for group in by_fingerprint.values():
        if len(group) < 2:
            continue
        if len({rec['donor_fingerprint'] for rec in group}) == 1:
            continue
        raise SystemExit(
            'monkey flip: the retarget made these phases identical, so they would '
            'play the same animation: ' + ', '.join(rec['clip'] for rec in group))
