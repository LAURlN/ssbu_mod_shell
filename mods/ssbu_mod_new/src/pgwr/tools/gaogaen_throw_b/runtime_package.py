"""v0.1.0: generate owned throw offsets and snapshot runtime source for offline compile.

No status ID is allocated, no shared source registration is changed, no installation.
"""
from pathlib import Path
import hashlib
import json
import re
import shutil
import struct
import sys
import argparse

ROOT = Path(__file__).resolve().parents[4]
LAB = ROOT.parents[1]
sys.path[:0] = [str(ROOT / 'src/pgwr/tools'), str(ROOT / 'tools')]
import prc
import pipeline

def digest(path): return hashlib.sha256(path.read_bytes()).hexdigest()

def main():
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument('--check', action='store_true')
    args = args.parse_args()
    pipeline.check_pins()
    labels = {}
    for line in (ROOT / 'dumps/scripts/ParamLabels.csv').read_text().splitlines():
        a, _, b = line.partition(',')
        if a.startswith('0x'): labels[int(a, 16)] = b
    def convert(node):
        tag, value = node
        if tag == 'struct': return {labels.get(k, hex(k)): convert(v) for k, v in value}
        if tag == 'list': return [convert(v) for v in value]
        if tag == 'hash': return labels.get(value, hex(value))
        return value
    table = convert(prc.read(pipeline.ARC / 'fighter/common/param/fighter_param_thrown.prc'))['fighter_param_thrown_table']
    binding = ROOT / 'builds/.cache/gaogaen_throw_b/cargo-home/git/checkouts/skyline-smash-f820da3599566683/315e4e8/src/lua_const.rs'
    constants = {name: int(value, 0) for name, value in re.findall(
        r'^\s+(FIGHTER_KIND_\w+): (0x[0-9a-fA-F]+|\d+),', binding.read_text(), re.M)}
    assert len(table) == 94
    for index, row in enumerate(table):
        assert constants[row['fighter_kind'].upper()] == index, row['fighter_kind']
    donor = next(row for row in table if row['fighter_kind'] == 'fighter_kind_gaogaen')
    assert len(donor['offset_b']) == 282
    vectors = [donor['offset_b'][i:i+3] for i in range(0, 282, 3)]
    source = '//! Generated by gaogaen_throw_b/runtime_package.py; do not hand edit.\n'
    source += '//! Exact vanilla 13.0.4 donor offsets, no global PRC override.\n'
    source += 'pub const BACK_OFFSETS: [[f32; 3]; 94] = [\n'
    for vector in vectors:
        source += '    [' + ', '.join('f32::from_bits(0x%08x)' % struct.unpack('<I', struct.pack('<f', x))[0] for x in vector) + '],\n'
    source += '];\n'
    output = ROOT / 'src/pgwr/plugin/src/status/gaogaen_throw_b_data.rs'
    plugin = ROOT / 'src/pgwr/plugin'
    private = ROOT / 'builds/.cache/gaogaen_throw_b/runtime-plugin'
    if args.check:
        assert output.read_text() == source, 'Owned donor offset bits changed'
        for part in ('acmd/gaogaen_throw_b.rs', 'status/gaogaen_throw_b.rs', 'status/gaogaen_throw_b_data.rs'):
            assert digest(plugin / 'src' / part) == digest(private / 'src' / part), part
        print('PASS donor pins, 94 row mappings, 282 float bits and compiled owned source equality.')
        return
    assert not private.exists(), 'Keep compile snapshots immutable; use a new task cache name for a changed snapshot'
    output.write_text(source)
    private.mkdir(parents=True)
    for name in ('Cargo.toml', 'Cargo.lock'): shutil.copyfile(plugin / name, private / name)
    shutil.copytree(plugin / 'src', private / 'src')
    acmd = private / 'src/acmd/mod.rs'
    text = acmd.read_text()
    if 'pub mod gaogaen_throw_b;' not in text:
        text = text.replace('pub fn install() {', 'pub mod gaogaen_throw_b;\n\npub fn install() {', 1)
    assert text.count('pub fn install() {') == 1
    text = text.replace('pub fn install() {', 'pub fn install() {\n    gaogaen_throw_b::install();', 1)
    acmd.write_text(text)
    status = private / 'src/status/mod.rs'
    text = status.read_text()
    assert 'mod gaogaen_throw_b;' not in text and text.count('pub fn install() {') == 1
    text = text.replace('pub fn install() {', 'pub mod gaogaen_throw_b;\n\npub fn install() {', 1)
    text = text.replace('pub fn install() {', 'pub fn install() {\n    gaogaen_throw_b::install();', 1)
    status.write_text(text)
    report = {'state': 'PENDING allocation and checks', 'status_allocation': None,
        'native_accessor_alias': {'0x4c': '0x4b'}, 'native_direction': 1,
        'table_rows_checked_against_pinned_runtime_constants': len(table),
        'owned_offset_source': {'path': output.relative_to(ROOT).as_posix(), 'sha256': digest(output)},
        'runtime_source': {'path': 'src/pgwr/plugin/src/status/gaogaen_throw_b.rs',
            'sha256': digest(plugin / 'src/status/gaogaen_throw_b.rs')},
        'private_snapshot': private.relative_to(ROOT).as_posix(),
        'snapshot_files': [{'path': p.relative_to(private).as_posix(), 'sha256': digest(p)}
            for p in sorted(private.rglob('*')) if p.is_file()]}
    (ROOT / 'evidence/2026-10-02_pgwr_gaogaen_throw_b/RUNTIME_SOURCE.json').write_text(json.dumps(report, indent=2) + '\n')
    print('94 row-kind mappings checked; 282 donor float bits generated; private source snapshot prepared.')

if __name__ == '__main__': main()
