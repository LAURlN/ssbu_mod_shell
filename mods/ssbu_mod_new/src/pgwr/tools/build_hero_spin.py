"""Retarget Mii Swordfighter's Hero's Spin (Hi3) onto Mythra c06 and c07.

Used by ``build.py`` so the ``mythra`` module in the plugin has real animation to
play. The moves themselves are in ``plugin/src/mythra/hero_spin.rs``; this only
produces the four clips that status machine asks for.

Provenance: the donor project
``mod_files/mythra_gamewatch_swap/tools/build_hero_spin3_assets.py`` does the
same retarget for its own ``c07``. Its low-level helpers live in
``build_hero_spin_assets.py`` in the same folder and are imported here rather
than reimplemented, because they are the parts that were actually debugged -
transform round-trip comparison, the visibility/material group layout check, the
skeleton-intersection check. Copying them would mean a second copy that can drift
from the one the donor validated on hardware.

What this adds over the donor is that it writes **both** c06 and c07, and that
it writes into this project's own package tree.

# Why no motion-list surgery is needed

The donor defines four Mii motion kinds and patches Mythra's list to point at
newly named clips. This mod does not, because the plugin never asks for a Mii
motion name. ``hero_spin.rs`` calls::

    MotionModule::change_motion(boma, Hash40::new("special_hi_start"), ...)
    ... "special_air_hi1" ... "special_air_hi_jump" ... "special_air_hi_end"

Those four are Mythra's own existing motion kinds, which already point at four
existing files in her own costume folder. So the retarget overwrites the *clip
behind* a stock motion kind and the motion list is left byte-identical.

Three consequences, all of them the reason this is simpler than the donor:

* no new motion entries, so no ``config.json`` declaration - every file written
  here replaces a file the base game already has, and ``build_config_json``'s
  "every new file must be declared" check stays satisfied without changes;
* no risk of a motion list that desyncs from the clips, because it is not
  touched;
* ``c00``-``c05`` are untouched by construction: nothing outside the two slots
  passed in is ever opened for writing.
"""
from pathlib import Path
import os
import sys

TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parents[2]
EXPORT = Path(os.environ.get('MGW_EXPORT', ROOT / 'dumps' / 'arc'))

# The donor's validated helpers. Absolute path into the sibling project rather
# than a relative one, because this folder is regenerated by nothing and the
# donor's is not guaranteed to sit next to it after a move.
SWAP_TOOLS = ROOT / 'src' / 'mgw_swap' / 'tools'
sys.path.insert(0, str(SWAP_TOOLS))
sys.path.insert(0, str(SWAP_TOOLS / 'vendor'))

import ssbh_data_py as s          # noqa: E402  (vendored by the donor)
import build_hero_spin_assets as base  # noqa: E402  (the donor's helpers)

DONOR_MOTION = EXPORT / 'fighter' / 'miiswordsman' / 'motion' / 'body' / 'c00'

# Mii motion kind, Mii clip, Mythra motion kind, Mythra clip.
#
# The Mythra column is what `hero_spin.rs` actually requests; the Mii column is
# only read to confirm the donor's list still names the clip we are copying, so
# a donor dump change fails here instead of shipping silently.
MOTIONS = (
    ('special_hi3_start', 'd02specialhi3start.nuanmb',
     'special_hi_start', 'd02specialhistart.nuanmb'),
    ('special_hi3_hold', 'd02specialhi3hold.nuanmb',
     'special_air_hi1', 'd02specialairhi1.nuanmb'),
    ('special_hi3', 'd02specialhi3.nuanmb',
     'special_air_hi_jump', 'd02specialairhijump.nuanmb'),
    ('special_air_hi3', 'd02specialairhi3.nuanmb',
     'special_air_hi_end', 'd02specialairhiend.nuanmb'),
)

# Pinned from the donor's build_hero_spin3_assets.py, which recorded them when
# the user supplied the three ground Hi3 clips that were missing from the dump.
# If the local Mii dump changes, this retarget changes with it, so it has to
# fail here rather than downstream.
DONOR_SHA256 = {
    'd02specialhi3start.nuanmb':
        '4351ef1fd837712a244a0ddf53945abbe7321b0ee7842e113ef45c64fad7d24c',
    'd02specialhi3hold.nuanmb':
        'e6049cc8622af5ade38e7a8f0b5d9f05c79b4c8a5502b37d87267cf63ce4b3be',
    'd02specialhi3.nuanmb':
        'b6b3c3b7edcae3b3bd8b098cecf216b093d19ca27549b2cb76cbc33711dcee4f',
    'd02specialairhi3.nuanmb':
        '9cc205a67e19e2c9eec38283586fa02a03955d81a55cbba1cc82fa082cf20b88',
}


def fail(message):
    raise SystemExit(f'hero spin: {message}')


def sha(path):
    import hashlib
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def stock_motions(slot):
    """Mythra's own motion list for `slot`, straight from the dump."""
    path = EXPORT / 'fighter' / 'elight' / 'motion' / 'body' / slot / 'motion_list.bin'
    if not path.is_file():
        fail(f'no stock Mythra motion list for {slot}: {path}')
    return path


def skeleton_bones(slot):
    """Bone names in Mythra's own skeleton for `slot`.

    Read per slot rather than assumed identical between c06 and c07. The donor
    measured c06 and c07 as byte-identical, but reading the real file means a
    dump where that stops being true produces a build that follows the
    skeleton rather than one that quietly writes transforms for bones that are
    not there.
    """
    path = EXPORT / 'fighter' / 'elight' / 'model' / 'body' / slot / 'model.nusktb'
    if not path.is_file():
        fail(f'no stock Mythra skeleton for {slot}: {path}')
    skel = s.skel_data.read_skel(str(path))
    return {b.name for b in skel.bones}


def retarget_one(motion, slot, out_dir, donor_list, stock, bones):
    """Write one retargeted clip, and prove it round-trips."""
    donor_slot, donor_file, stock_slot, stock_file = motion

    src = DONOR_MOTION / donor_file
    if not src.is_file() or sha(src) != DONOR_SHA256[donor_file]:
        fail(f'missing or changed donor clip: {src}')

    # The file this overwrites has to exist in the dump, or "we replaced a stock
    # clip" is false and the new file would be an undeclared addition that
    # ARCropolis never loads.
    stock_path = EXPORT / 'fighter' / 'elight' / 'motion' / 'body' / slot / stock_file
    if not stock_path.is_file():
        fail(f'no stock Mythra clip to replace: {stock_path}')

    # The donor's list must still name the clip we are copying, and Mythra's must
    # still name the file we are about to overwrite. Both are cheap and both turn
    # a renamed file into a build error instead of a missing animation.
    if donor_list.get(base.hash40(donor_slot), {}).get('animations') != (base.hash40(donor_file),):
        fail(f'donor motion {donor_slot} no longer names {donor_file}')
    if stock.get(base.hash40(stock_slot), {}).get('animations') != (base.hash40(stock_file),):
        fail(f'Mythra {slot} motion {stock_slot} no longer names {stock_file}')

    anim = s.anim_data.read_anim(str(src))
    groups = base.groups_by_type(anim)
    if set(groups) != set(base.EXPECTED_DONOR_GROUPS):
        fail(f'unexpected donor groups in {donor_file}: {sorted(groups)}')

    original = list(groups['Transform'].nodes)
    kept = [n for n in original if n.name in bones]
    dropped = sorted(n.name for n in original if n.name not in bones)
    # These counts are the donor's measured Mii-Hi3 shape. A different count
    # means the donor clip is not the one the retarget was written against.
    if len(original) != base.EXPECTED_DONOR_TRANSFORM_TRACKS:
        fail(f'{donor_file}: {len(original)} transform tracks, expected '
             f'{base.EXPECTED_DONOR_TRANSFORM_TRACKS}')
    if dropped != sorted(base.EXPECTED_DROPPED_TRACKS):
        fail(f'{donor_file}: dropped tracks {dropped}, expected '
             f'{sorted(base.EXPECTED_DROPPED_TRACKS)}')

    intended = base.collapse_series(base.node_series(kept))
    frame_count = int(round(anim.final_frame_index)) + 1

    # Mythra's own Visibility and Material groups, from her stock idle. Without
    # this the clip would carry Mii's meshes and render nothing, or render
    # Mythra's model with Mii's material switches. Read fresh per clip.
    vis, mat, _ = base.read_recipient_groups()

    groups['Transform'].nodes = kept
    anim.groups = [groups['Transform'],
                   base.build_group(vis, frame_count),
                   base.build_group(mat, frame_count)]

    target = out_dir / stock_file
    anim.save(str(target))

    # Read back and prove the write is what we intended, rather than trusting
    # the save.
    check = s.anim_data.read_anim(str(target))
    found = base.groups_by_type(check)
    if set(found) != {'Transform', 'Visibility', 'Material'}:
        fail(f'wrong output groups in {target}')
    if int(round(check.final_frame_index)) + 1 != frame_count:
        fail(f'wrong frame count in {target}')
    if {n.name for n in found['Transform'].nodes} != {n.name for n in kept}:
        fail(f'wrong transform bones in {target}')
    reread = base.collapse_series(base.node_series(found['Transform'].nodes))
    for name in sorted(intended):
        difference = base.first_difference(name, intended[name], reread[name])
        if difference:
            fail(f'round-trip transform mismatch in {target}: {difference}')
    if len(found['Visibility'].nodes) != base.EXPECTED_VIS_NODES:
        fail(f'wrong visibility node count in {target}')
    if len(found['Material'].nodes) != base.EXPECTED_MAT_NODES:
        fail(f'wrong material node count in {target}')

    return {
        'motion_kind': stock_slot,
        'clip': stock_file,
        'donor_clip': donor_file,
        'frames': frame_count,
        'transform_tracks': len(kept),
        'dropped_tracks': dropped,
        'sha256': sha(target),
    }


# `retarget_one` walks MOTIONS in order; this cursor keeps that explicit rather
# than a mutable default argument, and is reset per slot.
def build_slot(slot, out_root):
    """Retarget all four phases for one Mythra costume. Returns a report."""
    out_dir = out_root / 'fighter' / 'elight' / 'motion' / 'body' / slot
    out_dir.mkdir(parents=True, exist_ok=True)

    stock = read_motions(stock_motions(slot))
    donor = read_motions(DONOR_MOTION / 'motion_list.bin')
    bones = skeleton_bones(slot)

    clips = [retarget_one(motion, slot, out_dir, donor, stock, bones)
             for motion in MOTIONS]

    # The whole argument for "no motion-list surgery" is that these four kinds
    # still point where they did. Checked against the file that shipped in the
    # dump, which this function never writes.
    for _, _, stock_slot, stock_file in MOTIONS:
        if stock[base.hash40(stock_slot)]['animations'] != (base.hash40(stock_file),):
            fail(f'{slot}: {stock_slot} moved during the build')

    return {'slot': slot, 'skeleton_bones': len(bones), 'clips': clips}


def read_motions(path):
    """motion kind hash -> {'animations': (...)} from a motion_list.bin.

    The donor's parser, which returns `(magic, motion_path, motions)`. Only the
    clip names are needed here; the raw entry bytes are irrelevant because this
    tool never rewrites a motion list.
    """
    _, _, motions = base.parse_mlist(path)
    return motions
