//! Per-move ACMD ports: Pyra (`eflame`) script names -> Mr. Game & Watch sources.
//!
//! # How gating works here
//!
//! Every install in this tree builds a `smashline::Agent` for `eflame` and calls
//! `.set_costume(crate::TARGET_COSTUMES.to_vec())`. In the locked smashline
//! (`be3ef308`, crates/smashline/src/builder.rs) that stores a `Costume` on the
//! agent entry, and `install_script` (src/create_agent.rs) applies it like this:
//!
//! ```text
//! let costume = get_agent_costume(agent.battle_object as *const BattleObject).unwrap_or(0);
//! let has_costume = has_costume(agent_hash, costume);
//! let c = script.costume.as_slice();
//! if has_costume && !c.contains(&(costume as usize)) { continue; }
//! if !has_costume &&   !c.is_empty()                { continue; }
//! agent.sv_set_function_hash(unreachable_smashline_script, *hash);
//! ```
//!
//! So for an eflame agent created in c00-c05, `has_costume` is false and our
//! `Costume` is non-empty, so the `continue` fires and `sv_set_function_hash` is
//! never reached: the stock Pyra script pointer stays in place. We are not
//! overriding Pyra's script for everybody and branching inside it. That is why
//! these functions contain no costume `if`, and why there is no `else` branch
//! that could drift from vanilla.
//!
//! **That is read from source, not proven on hardware.** `gate_trace` below exists
//! to turn the first hardware test into a log reading rather than a judgement call.
//!
//! # Generation
//!
//! The ported bodies are generated by `tools/gen_acmd.py` from the dumps and are
//! not hand-edited. Every transformation the generator applies is listed as a rule
//! (R1-R7) in that file, and each drop is recorded in the `GEN-NOTES` header of
//! the file it happened in. `generated-manifest.json` records the donor script and
//! status list per group. Run with `--check` to prove the checked-in files still
//! match the generator.
//!
//! # What could not be ported
//!
//! G&W's dump constants are absolute, not symbolic, so they are not reusable:
//!
//! * `FIGHTER_GAMEWATCH_INSTANCE_WORK_ID_INT_NORMAL_WEAPON_KIND` is `0x100000BD`,
//!   a raw WorkModule index. eflame's own ranges are float `0x4B`-`0x4C` and int
//!   `0x100000BF`-`0x100000C3`. Rule R6 drops these writes; the jab's prop and
//!   the aerials' weapon-kind switch are therefore absent, pending phase 4.
//! * `FIGHTER_GAMEWATCH_GENERATE_ARTICLE_*` runs 0-8; eflame's
//!   `ARTICLE_TERM` is `0x5`, so she has 0-4. Rule R1 drops the calls. G&W's
//!   forward air drops a bomb and his up air breathes; without the article those
//!   are body-only aerials until phase 4.
//! * `gamewatch::ST_*` status kinds are absent from every non-special script
//!   (verified by `tools/analyse_port.py`), so no status translation is needed
//!   for phase 2 at all.
//!
//! G&W's *bones* are not a problem: the only ATTACK bone any of these scripts
//! uses is `top`, which is Smash's built-in fighter-top anchor rather than a
//! skeleton bone, so hitbox placement does not depend on the grafted skeleton.

