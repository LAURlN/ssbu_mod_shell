/// Proof that the costume gate is live, readable from the log rather than by eye.
///
/// The first hardware test came back "kinda hard to tell", which cannot
/// distinguish a working gate from a gate that silently failed open. This
/// callback is registered on the *same* gated agent as the ACMD overrides, so
/// smashline only ever installs it for c06/c07. If a line appears naming a
/// costume, the gate is holding and the overrides are on that fighter. The
/// absence of lines for c00-c05 in the same match is the negative control.
///
/// `battle_object` is the agent's object id, not a stable handle, so it is only
/// used as a label and never retained.
static mut GATE_SEEN: [bool; 8] = [false; 8];

unsafe extern "C" fn gate_trace(agent: &mut L2CAgent) {
    let colour = WorkModule::get_int(
        agent.module_accessor,
        *FIGHTER_INSTANCE_WORK_ID_INT_COLOR,
    );
    let id = (*agent.battle_object).battle_object_id as usize;
    if id < 8 && !GATE_SEEN[id] {
        GATE_SEEN[id] = true;
        crate::diagnostic!(println!(
            "{} GATE ACTIVE: entry {} running c06/c07 overrides, reported colour {}",
            crate::LOG, id, colour
        ));
    }
}

pub fn install() {
    gaogaen_throw_b::install();
    generated::ground::install();
    generated::rapid::install();
    generated::aerial::install();
    generated::grab::install();
    generated::common::install();
    attack_air_f::install();
    // The jab is Chrom's. Its weapon is Pyra's own esword, so no clone is involved
    // and nothing is registered in `crate::article` for it; this is the ACMD half.
    chrom_jab::install();
    // Side-B is Monkey Flip; its scripts live with its status machine's move,
    // not with the generated normals. Registered on the same gated agent.
    monkey_flip::install();
    // Back air is Pikachu's, with its landing; High priority over the generated
    // G&W AttackAirB (which spawned the turtle article) and over the generated
    // G&W LandingAirB. Same gated agent.
    pikachu_attack_air_b::install();
    // Down tilt is R.O.B.'s; High priority over the generated G&W AttackLw3 above.
    robot_attack_lw3::install();
    // Up tilt is Snake's, with his own clip, cancel frame and sounds; High priority
    // over the generated G&W AttackHi3. Same gated agent as everything else here.
    snake_attack_hi3::install();
    // Down throw is Snake's, with his own clip, cancel frame 48 and his own grab
    // tones; High priority over the generated G&W ThrowLw. Same gated agent.
    snake_throw_lw::install();
    // Forward smash is Little Mac's, with its charge hold. High priority over the
    // generated G&W AttackS4/AttackS4Charge, which spawned his prop.
    littlemac_attack_s4::install();
    // Up-B is G&W's Fire: body scripts plus the rescue/parachute visibility scripts,
    // generated like the normals (tools/gen_acmd.py R27-R30); statuses in status::special_hi.
    generated::special::install();

    // Same gate as the ACMD overrides, so this line only ever appears for c06/c07.
    #[cfg(feature = "logging")]
    Agent::new("eflame")
        .set_costume(crate::TARGET_COSTUMES.to_vec())
        .on_line(Main, gate_trace)
        .install();
}
