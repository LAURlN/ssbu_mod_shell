"""Generate trace/src/work_ids.rs from skyline-smash's lua_const.rs.

The trace plugin records WorkModule values by id. This script copies the
instance-work ids (common to all fighters, plus Pyra/Mythra/Element specific)
out of the pinned skyline-smash checkout so the trace can print readable names.

Only *instance* work is covered. Status work and int64 work are deliberately
left out until their valid id ranges are established (see trace/README.md).

Usage: python pyra_mythra_clone/tools/gen_trace_work_ids.py [path/to/lua_const.rs]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT = Path.home() / '.cargo/git/checkouts/skyline-smash-f820da3599566683/315e4e8/src/lua_const.rs'
OUT = ROOT / 'trace/src/work_ids.rs'

GROUPS = [
    # (rust table name, name prefix)
    ('COMMON', 'FIGHTER_INSTANCE_WORK_ID_'),
    ('EFLAME', 'FIGHTER_EFLAME_INSTANCE_WORK_ID_'),
    ('ELIGHT', 'FIGHTER_ELIGHT_INSTANCE_WORK_ID_'),
    ('ELEMENT', 'FIGHTER_ELEMENT_INSTANCE_WORK_ID_'),
]
KINDS = (('_INT_', 'Int'), ('_FLAG_', 'Flag'), ('_FLOAT_', 'Float'))


def main():
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
    text = source.read_text(encoding='utf8')
    consts = re.findall(r'^\s+([A-Z0-9_]+): (0x[0-9A-Fa-f]+|-?\d+),', text, re.M)
    lines = [
        '// Generated by tools/gen_trace_work_ids.py from skyline-smash lua_const.rs.',
        '// Do not edit by hand; rerun the script.',
        '',
        '#[derive(Clone, Copy)]',
        'pub enum W { Int, Flag, Float }',
        '',
    ]
    total = 0
    for table, prefix in GROUPS:
        rows = []
        for name, value in consts:
            if not name.startswith(prefix):
                continue
            rest = name[len(prefix) - 1:]  # keep the leading underscore for the kind match
            kind = next((k for marker, k in KINDS if rest.startswith(marker)), None)
            if kind is None:
                continue  # *_TERM, *_NONE and similar markers are not ids
            if rest.endswith('_TERM') or rest.endswith('_NONE') or rest.endswith('_NUM'):
                continue
            short = name[len(prefix):]
            if short in ('INT_START', 'FLAG_START', 'FLOAT_START') or short.endswith('PRE_START'):
                continue  # range markers, not variables
            number = int(value, 0)
            valid = {'Int': 0x10000000 <= number < 0x20000000,
                     'Flag': 0x20000000 <= number < 0x30000000,
                     'Float': 0 <= number < 0x1000}[kind]
            if not valid:
                raise ValueError('unexpected id range for {} = {:#x}'.format(name, number))
            rows.append((name[len(prefix):], number, kind))
        rows.sort(key=lambda r: (r[2], r[1], r[0]))
        total += len(rows)
        lines.append('pub static {}: &[(&str, i32, W)] = &['.format(table))
        for short, number, kind in rows:
            lines.append('    ("{}", {:#x}, W::{}),'.format(short, number, kind))
        lines.append('];')
        lines.append('')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines), encoding='utf8')
    print('wrote', OUT, 'with', total, 'ids')


if __name__ == '__main__':
    main()
