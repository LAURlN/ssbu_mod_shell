"""Generate the sourced Mii air gravity used by Mythra c07 Hi3."""
from pathlib import Path
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'mod_files/mythra_gamewatch_swap/tools/runtime_lib'))
import pyprc

SOURCE = ROOT / 'export/fighter/common/param/fighter_param.prc'
OUT = ROOT / 'mod_files/mythra_gamewatch_swap/src/hero_spin3_params.rs'
MANIFEST = ROOT / 'references/miiswordsman_special_hi3/kinetic_manifest.json'
EXPECTED_SHA256 = '87fcf45c456d36d3f8a29a5a6d1f847124d55f8fb3db84efdc8f1490edad55c2'

def main():
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    if digest != EXPECTED_SHA256:
        raise SystemExit(f'Common fighter parameters changed: {digest}')
    rows = pyprc.param(str(SOURCE))[pyprc.hash('fighter_param_table')]
    values = {}
    for fighter in ('miiswordsman', 'elight'):
        kind = pyprc.hash('fighter_kind_' + fighter)
        row = next(r for r in rows if str(r[pyprc.hash('fighter_kind')].value) == str(kind))
        values[fighter] = {name: row[pyprc.hash(name)].value
                           for name in ('air_accel_y', 'air_speed_y_stable')}
    lines = [
        '// Generated by tools/extract_hero_spin3_params.py from the game dump.',
        '// Source: export/fighter/common/param/fighter_param.prc',
        f'// SHA-256: {digest}',
        f"pub const MGW_HI3_AIR_ACCEL_Y: f32 = {values['miiswordsman']['air_accel_y']!r};",
        f"pub const MGW_HI3_AIR_SPEED_Y_STABLE: f32 = {values['miiswordsman']['air_speed_y_stable']!r};",
    ]
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    MANIFEST.write_text(json.dumps({'source': str(SOURCE.relative_to(ROOT)),
                                    'sha256': digest, 'values': values}, indent=2) + '\n', encoding='utf-8')
    print('Wrote', OUT)
    print('Wrote', MANIFEST)

if __name__ == '__main__':
    main()
