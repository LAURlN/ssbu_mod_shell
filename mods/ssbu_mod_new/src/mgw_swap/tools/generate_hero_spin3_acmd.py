"""Pin the three Hi3 game ACMD bodies from the local Mii Swordfighter dump."""
from pathlib import Path
import hashlib
import re

root = Path(__file__).resolve().parents[3]
dump = root / 'SSBU-Dumped-Scripts-main/smashline/lua2cpp_miiswordsman/miiswordsman'
out = root / 'mod_files/mythra_gamewatch_swap/src/hero_spin3_acmd.rs'
specs = (
    ('SpecialHi3Start.txt', 'game_specialhi3start', 'hi3_ground_start', 'game_specialhistart'),
    ('SpecialHi3.txt', 'game_specialhi3', 'hi3_ground_spin', 'game_specialairhijump'),
    ('SpecialAirHi3.txt', 'game_specialairhi3', 'hi3_air_spin', 'game_specialairhiend'),
)
pieces = ['// Generated by tools/generate_hero_spin3_acmd.py from local dumped game ACMD.\n']
for filename, donor, recipient, vanilla in specs:
    data = (dump / filename).read_bytes()
    body = data.decode('utf-8')
    pattern = rf'unsafe extern "C" fn {donor}\(agent: &mut L2CAgentBase\) \{{'
    match = re.search(pattern, body)
    if not match:
        raise SystemExit(f'Missing {donor} in {filename}')
    depth = 1
    end = match.end()
    while depth:
        if body[end] == '{':
            depth += 1
        elif body[end] == '}':
            depth -= 1
        end += 1
    extracted = body[match.start():end].replace(f'fn {donor}(', f'fn {recipient}(', 1)
    opening = extracted.find('{') + 1
    gate = f'\n    if !is_target(agent.module_accessor) {{ vanilla(agent, "{vanilla}"); return; }}'
    extracted = extracted[:opening] + gate + extracted[opening:]
    pieces.append(f'// {filename} SHA256 {hashlib.sha256(data).hexdigest()}\n{extracted}\n')
out.write_text('\n'.join(pieces), encoding='utf-8')
print(f'Generated {out} ({out.stat().st_size} bytes)')
